"""Collect every validation result into one scorecard (markdown) and one flat residual table
(JSON lines) -- the table is the training/target set for a later ML-correction layer.

    python scripts/validation_scorecard.py  ->  forward_results/SCORECARD.md, residuals.jsonl
"""
import json
import os

import numpy as np

R = "forward_results"


def load(name):
    p = os.path.join(R, name)
    return json.load(open(p)) if os.path.exists(p) else None


res = []           # flat residual rows: quantity, ion, host, measured, model, log10 ratio, src
md = ["# Validation scorecard", "",
      "Model vs measurement, every check in one place.  `x` = model / measured.  Generated by "
      "`scripts/validation_scorecard.py` from the JSON files in this folder.", ""]

v = load("validation.json")
if v:
    rows = [r for r in v if r.get("band_reproduced") is not None]
    ok = sum(1 for r in rows if r["band_reproduced"])
    md += [f"## Gain bands of known fibre media: {ok} / {len(rows)} reproduced", ""]
    for r in v:
        if r.get("model_tau_ms") and r.get("exp_tau_ms"):
            res.append(dict(quantity="tau_ms(validation)", ion=r["ion"], host=r["family"], item=str(r["transition"]),
                            measured=r["exp_tau_ms"], model=r["model_tau_ms"], src="fiber_validation.py"))

lv = load("level_validation.json")
if lv:
    for g, title in (("lifetime", "Lifetimes"), ("cross_section", "Peak cross sections")):
        rs = [r for r in lv if r["group"] == g]
        if not rs:
            continue
        x = np.array([r["ratio"] for r in rs])
        within = np.mean(np.abs(np.log10(x)) <= np.log10(1.3)); within2 = np.mean(np.abs(np.log10(x)) <= np.log10(2))
        md += [f"## {title}: {len(rs)} checks, {within:.0%} within 30 %, {within2:.0%} within 2x, "
               f"rms {np.sqrt(np.mean(np.log10(x) ** 2)):.2f} decades", "",
               "| ion | host | item | measured | model | x | source |", "|---|---|---|---|---|---|---|"]
        for r in rs:
            md.append(f"| {r['ion']} | {r['family']} | {r['item']} ({r['kind']}) | {r['measured']:.3g} | "
                      f"{r['model']:.3g} | {r['ratio']:.2f} | {r['src'][:60]} |")
            res.append(dict(quantity=f"{g}:{r['kind']}", ion=r["ion"], host=r["family"], item=r["item"],
                            measured=r["measured"], model=r["model"], src=r["src"]))
        md.append("")
    rs = [r for r in lv if r["group"] == "stark"]
    if rs:
        md += ["## Stark levels (cm^-1)", "", "| ion | host | item | measured | model | diff |", "|---|---|---|---|---|---|"]
        for r in rs:
            md.append(f"| {r['ion']} | {r['family']} | {r['item']} | {r['measured']:.0f} | {r['model']:.0f} | {r['diff']:+.0f} |")
            res.append(dict(quantity="stark_cm1", ion=r["ion"], host=r["family"], item=r["item"],
                            measured=r["measured"], model=r["model"], src=r["src"]))
        md.append("")
    rs = [r for r in lv if r["group"] == "laser_wavelength"]
    if rs:
        ok = sum(r["reproduced"] for r in rs)
        md += [f"## Demonstrated lasers inside a model gain window: {ok} / {len(rs)}", ""]
        for r in rs:
            md.append(f"- {'OK  ' if r['reproduced'] else 'MISS'} {r['ion']} {r['family']} {r['item']} "
                      f"{r['measured']:.0f} nm (pump {r['pump_nm']:.0f} nm)")
        md.append("")

sp = load("spectra_validation.json")
if sp:
    md += ["## Full spectra (digitised curves)", "",
           "| curve | integrated x | peak x | shape rms | peak model/meas nm | FWHM model/meas nm |",
           "|---|---|---|---|---|---|"]
    for r in sp:
        md.append(f"| {r['label']} | {r['scale_integrated']:.2f} | {r['peak_ratio']:.2f} | {r['shape_rms']:.2f} | "
                  f"{r['peak_model_nm']:.0f}/{r['peak_meas_nm']:.0f} | {r['fwhm_model_nm']:.0f}/{r['fwhm_meas_nm']:.0f} |")
        res.append(dict(quantity="spectrum_integrated", ion=r["ion"], host=r["family"], item=r["label"],
                        measured=1.0, model=r["scale_integrated"], src=r["src"]))
    md.append("")

dv = load("device_validation.json")
if dv:
    md += ["## Devices built to published geometry", "", "| device | variant | quantity | model | measured |", "|---|---|---|---|---|"]
    for r in dv:
        if "model_slope" in r:
            m = f"slope {r['model_slope']:.2f}" if r.get("model_slope") is not None else "no lasing"
            if r.get("model_threshold_W") is not None:
                m += f", thr {r['model_threshold_W']:.3g} W"
            e = (f"slope {r['measured_slope']:.2f}" if r.get("measured_slope") else "") + \
                (f", thr {r['measured_threshold_W']:.3g} W" if r.get("measured_threshold_W") else "")
        else:
            m, e = f"{r.get('model', float('nan')):.1f}", f"{r.get('measured', float('nan')):.1f}"
        md.append(f"| {r['case']} | {r['variant']} | {r['quantity']} | {m} | {e} |")
    md.append("")

cd = load("codoping_validation.json")
if cd:
    md += ["## Er,Pr:ZBLAN energy transfer (Golding 2000)", "", "| N_Er | N_Pr | 4I13/2 model/meas us | 4I11/2 model/meas us |",
           "|---|---|---|---|"]
    for r in cd["lifetimes"]:
        md.append(f"| {r['N_Er']:.1e} | {r['N_Pr']:.1e} | {r['tau13_model_us']:.0f} / {r['tau13_meas_us']:.0f} | "
                  f"{r['tau11_model_us']:.0f} / {r['tau11_meas_us']:.0f} |")
    md.append("")

ed = load("edfa_validation.json")
if ed:
    md += ["## Erbium-doped fibre amplifiers (Giles & Desurvire 1991)", "", "| case | model | measured |", "|---|---|---|"]
    for r in ed:
        md.append(f"| {r['case']} | {r['model']} | {r['measured']} |")
    md.append("")

vd = load("vendor_validation.json")
if vd:
    if vd.get("liekki"):
        md += ["## Commercial fibre cross sections (nLIGHT LIEKKI, metrics only)", "",
               "| curve | integrated x | peak x | peak shift nm | shape rms / ratio rms |", "|---|---|---|---|---|"]
        for r in vd["liekki"]:
            if "integrated_ratio" in r:
                md.append(f"| {r['curve']} | {r['integrated_ratio']:.2f} | {r['peak_ratio']:.2f} | "
                          f"{r['peak_shift_nm']:+.0f} | {r['shape_rms']:.2f} |")
                res.append(dict(quantity="vendor_xs_integrated", ion=r["ion"], host=r["host"], item=r["curve"],
                                measured=1.0, model=r["integrated_ratio"], src=r["src"]))
            else:
                md.append(f"| {r['curve']} | | | | ratio rms {r['rms_log10']:.2f} dec (bias {r['mean_log10']:+.2f}) |")
        md.append("")
    if vd.get("lvf"):
        ok = sum(r["reproduced"] for r in vd["lvf"])
        md += [f"## Le Verre Fluore demonstrated lines inside a model gain window: {ok} / {len(vd['lvf'])}", ""]
        for r in vd["lvf"]:
            md.append(f"- {'OK  ' if r['reproduced'] else 'MISS'} {r['ion']} {r['target_nm']:.0f} nm: {r['description']}"
                      + ("" if r["reproduced"] else f" (nearest window edge {r['nearest_window_edge_nm']:.0f} nm)"))
        md.append("")

gl = load("gap_law_check.json")
if gl:
    md += [f"## Multiphonon rates: gap law vs {gl['n']} measured rates, rms {gl['rms_log10_layne']:.2f} decades "
           f"(Layne glasses)", ""]

for r in res:
    try:
        r["log10_ratio"] = float(np.log10(r["model"] / r["measured"]))
    except Exception:
        r["log10_ratio"] = None
with open(os.path.join(R, "residuals.jsonl"), "w") as f:
    for r in res:
        f.write(json.dumps(r, default=float) + "\n")
open(os.path.join(R, "SCORECARD.md"), "w").write("\n".join(md) + "\n")
print(f"wrote {R}/SCORECARD.md and residuals.jsonl ({len(res)} residual rows)")
